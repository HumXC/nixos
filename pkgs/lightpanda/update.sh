#! /usr/bin/env nix-shell
#! nix-shell -i bash --pure --keep GITHUB_TOKEN -p nix curl cacert nix-prefetch-git jq

set -euo pipefail

cd $(readlink -e $(dirname "${BASH_SOURCE[0]}"))

repo="lightpanda-io/browser"
version="${1:-}"

curl_headers=(
  -H "Accept: application/vnd.github+json"
  -H "User-Agent: nix-lightpanda-update"
)

if [[ -n "${GITHUB_TOKEN:-}" ]]; then
  curl_headers+=( -H "Authorization: Bearer ${GITHUB_TOKEN}" )
fi

if [[ -z "$version" ]]; then
  version=$(
    curl -fsSL "${curl_headers[@]}" "https://api.github.com/repos/${repo}/releases" \
      | jq -r '[.[] | select(.tag_name | test("^v?[0-9]+\\.[0-9]+\\.[0-9]+$"))][0].tag_name'
  )
fi

version="${version#v}"

if [[ -z "$version" || "$version" == "null" ]]; then
  echo "Could not determine Lightpanda release version" >&2
  exit 1
fi

# linux

linux_x86_64_url="https://github.com/${repo}/releases/download/${version}/lightpanda-x86_64-linux"
linux_aarch64_url="https://github.com/${repo}/releases/download/${version}/lightpanda-aarch64-linux"

linux_x86_64_hash=$(nix-prefetch-url --type sha256 "$linux_x86_64_url")
linux_aarch64_hash=$(nix-prefetch-url --type sha256 "$linux_aarch64_url")

# use friendlier hashes
linux_x86_64_hash=$(nix --extra-experimental-features nix-command hash convert --to sri --hash-algo sha256 "$linux_x86_64_hash")
linux_aarch64_hash=$(nix --extra-experimental-features nix-command hash convert --to sri --hash-algo sha256 "$linux_aarch64_hash")

cat >sources.nix <<EOF
# Generated by ./update.sh - do not update manually!
# Last updated: $(date +%F)
{ fetchurl }:

{
  x86_64-linux = {
    version = "$version";
    src = fetchurl {
      url = "$linux_x86_64_url";
      hash = "$linux_x86_64_hash";
    };
  };
  aarch64-linux = {
    version = "$version";
    src = fetchurl {
      url = "$linux_aarch64_url";
      hash = "$linux_aarch64_hash";
    };
  };
}
EOF
